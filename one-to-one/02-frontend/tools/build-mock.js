// Builds mock/index.html from one-to-one.html so the local mock always uses the exact production CSS.
// Usage: node tools/build-mock.js   (run from the 02-frontend folder, or any folder – paths are relative to this file)
'use strict';
var fs = require('fs');
var path = require('path');
var base = path.join(__dirname, '..');
var layout = fs.readFileSync(path.join(base, 'one-to-one.html'), 'utf8');
var css = layout.slice(layout.indexOf('<style>') + 7, layout.indexOf('</style>')).split('.SCOPE ').join('.oto-scope ');

var page = [
  '<!doctype html>',
  '<html lang="en">',
  '<head>',
  '<meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  '<title>ESG 1-to-1 local mock</title>',
  '<!-- GENERATED by tools/build-mock.js – do not edit by hand. Local testing only: fictional data, nothing leaves the browser. -->',
  '<style>',
  'body { margin: 0; background: #eef2f5; }',
  '.mockbar { background: #3b3b3b; color: #fff; font: 12px "Segoe UI", Arial, sans-serif; padding: 6px 16px; display: flex; gap: 10px; align-items: center; flex-wrap: wrap; }',
  '.mockbar a { color: #fff; border: 1px solid #888; border-radius: 4px; padding: 2px 9px; text-decoration: none; }',
  '.mockbar a.on { background: #fff; color: #222; }',
  '.mockbar .sp { flex: 1; }',
  css,
  '</style>',
  '</head>',
  '<body>',
  '<div class="mockbar" id="mockbar"></div>',
  '<div class="oto-scope"><div class="oto" data-oto-root></div></div>',
  '<script src="../one-to-one.js"></script>',
  '<script src="mock-sharepoint.js"></script>',
  '<script>',
  '(function () {',
  "  var p = new URL(window.location.href).searchParams;",
  "  var as = p.get('as') || 'tl', xss = p.get('xss') === '1';",
  "  window.__otoXssFired = false; window.oto_xss = function () { window.__otoXssFired = true; };",
  "  var bar = document.getElementById('mockbar');",
  "  function link(label, params, on) { var a = document.createElement('a'); a.textContent = label; var u = new URL(window.location.href); u.search = ''; Object.keys(params).forEach(function (k) { u.searchParams.set(k, params[k]); }); a.href = u.toString(); if (on) { a.className = 'on'; } bar.appendChild(a); }",
  "  var t = document.createElement('span'); t.textContent = 'LOCAL MOCK – fictional data, nothing is sent anywhere. View as:'; bar.appendChild(t);",
  "  OTO_MOCK.USERS.forEach(function (u) { link((u.owner ? 'Team Leader' : u.title) + (u.label ? ' (' + u.label + ')' : ''), xss ? { as: u.key, xss: '1' } : { as: u.key }, u.key === as); });",
  "  var sp = document.createElement('span'); sp.className = 'sp'; bar.appendChild(sp);",
  "  link(xss ? 'XSS test data: ON' : 'XSS test data: off', xss ? { as: as } : { as: as, xss: '1' }, xss);",
  "  var r = document.createElement('a'); r.href = '#'; r.textContent = 'Reset data'; r.addEventListener('click', function (e) { e.preventDefault(); OTO_MOCK.reset(); window.location.reload(); }); bar.appendChild(r);",
  "  var inst = window.ESGOneToOne(OTO_MOCK.ctx(as, xss));",
  "  window.__otoInstance = inst;",
  "  inst.onInitialize();",
  '})();',
  '</script>',
  '</body>',
  '</html>',
  ''
].join('\n');
fs.writeFileSync(path.join(base, 'mock', 'index.html'), page);
console.log('mock/index.html written (' + page.length + ' bytes)');
